r"""atlas_project -- WHICH paper atlas a tool works on, and how that atlas is configured.

An atlas PROJECT is one folder:

    atlas.toml                       title, topic labels and groups, program tasks, pipeline switches (all optional)
    papers/<topic>.json              one row per paper (key, title, year, venue, status, doi / arxiv_id, summary, ...)
    refs/<topic>/verified_refs.json  each paper's API record (tools/verify_refs.py format: authors, abstract, ...)
    lexicon/*.json                   terms, each with verbatim <= 15-word quotes from the papers
    index/                           GENERATED by build_bwm.py: papers.json, browser.html (+ its 2 sidecars), ATLAS.xlsx
    figures/                         GENERATED citation maps

plus ONE folder of PDFs (atlas.toml `[paths] papers`, default `pdfs` inside the project), whose caches sit BESIDE it:
`<pdfs>_text` (page text + BM25 index), `_ocr`, `_html`, `_embed`, `_figures`, and `_atlas` (the pipeline's state and
logs, tools/atlas.py).

    ATLAS_PROJECT=<folder>   which project; else the nearest folder holding atlas.toml from the working directory up;
                             else, in this repository, the BlueBoat world-model atlas (report/boat_world_model)
    ATLAS_PAPERS=<folder>    its PDFs; else atlas.toml [paths] papers; else (BlueBoat) $SVFR_BWM_PAPERS / the found copy

WHY (owner, 2026-10-15): "make a generalized version I can hand off to lab mates so they can add their papers and
customize it for their usage". Every paper tool hard-coded `report/boat_world_model` and the BlueBoat PDF folder, and
the program's own vocabulary -- the page title, the citation map's seven topic groups, the eighteen program tasks, the
zip's name -- sat in code. All of it now comes from here: the BlueBoat values live in report/boat_world_model/atlas.toml
(its build is unchanged: `build_bwm.py check`), a new project gets the generic defaults below. Pure stdlib (tomllib:
Python 3.11+), so an exported kit carries it unchanged.
"""
from __future__ import annotations

import copy
import os
import re
import tomllib
from functools import lru_cache
from pathlib import Path
from typing import Callable, Dict, List, Optional, Tuple

ROOT = Path(__file__).resolve().parent.parent
CONFIG = "atlas.toml"
ENV_PROJECT, ENV_PAPERS = "ATLAS_PROJECT", "ATLAS_PAPERS"
BLUEBOAT = ROOT / "report" / "boat_world_model"
#: the citation map draws one panel per group (and one for the backbone): more groups than this do not fit
MAX_GROUPS = 7

GENERIC: Dict[str, object] = {
    "atlas": {"title": "Paper Atlas", "subtitle": "", "short_name": "atlas",
              "bundle_title": "Paper atlas -- portable bundle"},
    "paths": {"papers": ""},
    "topics": {},
    "groups": [],
    "tasks": [],
    "pipeline": {
        "gpu": "auto",               # auto | yes | no: embeddings, figure detection and the lookup's dense half
        "python_gpu": "",            # the interpreter with torch for those stages ("" = the one running atlas.py)
        "embed_model": "auto",       # auto = nemotron-1b with a GPU, minilm (22M, fine on a CPU) without
        "figures": "auto",           # auto = DocLayout-YOLO with a GPU, the model-free heuristic without; off = skip
        "ocr": True,                 # scanned pages: RapidOCR
        "arxiv_html": False,         # arXiv's LaTeX HTML (equations, sections): one page per 15 s, so off by default
        "facts": True,               # per-paper facts (code links, datasets, metrics, hardware, ...) with evidence
        "meta": True,                # OpenAlex: venue, dates, citation counts, reference lists (network)
        "github_stars": False,       # GitHub stars of code links (needs a `gh` login)
        "semantic_scholar": False,   # Semantic Scholar citation counts (keyless calls are rate-limited)
        "terms": True,               # the auto glossary: abbreviations the papers define, with verbatim quotes
        "bundle": True,              # rebuild the portable .zip at the end of `update`
        "bundle_pdfs": True,
        "bundle_figures": True,
    },
}
_STR_KEYS = {"atlas": ("title", "subtitle", "short_name", "bundle_title", "contact_email"), "paths": ("papers",)}


class ConfigError(ValueError):
    """atlas.toml says something this module cannot use; the message names the key and what it expected."""


def engine_dir() -> Path:
    """The atlas builder's CODE (build_bwm.py and its siblings): report/boat_world_model in this repository,
    engine/atlas in an exported kit (tools/atlas.py export-kit)."""
    for c in (ROOT / "engine" / "atlas", BLUEBOAT):
        if (c / "build_bwm.py").is_file():
            return c
    return BLUEBOAT


ENGINE = engine_dir()


def find_project(start: Path) -> Optional[Path]:
    """The nearest folder at or above `start` holding atlas.toml, or None."""
    p = Path(start).resolve()
    for c in (p, *p.parents):
        if (c / CONFIG).is_file():
            return c
    return None


def project_dir() -> Path:
    """The project every tool works on (resolved per call: a test or the pipeline may set ATLAS_PROJECT)."""
    v = os.environ.get(ENV_PROJECT, "").strip()
    if v:
        return Path(v).expanduser().resolve()
    here = find_project(Path.cwd())
    if here is not None:
        return here
    return BLUEBOAT


def is_blueboat(project: Path) -> bool:
    try:
        return Path(project).resolve() == BLUEBOAT.resolve()
    except OSError:
        return False


def _merge(base: dict, over: dict) -> dict:
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = _merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def _validate(cfg: dict, where: str) -> dict:
    for table, keys in _STR_KEYS.items():
        if not isinstance(cfg.get(table), dict):
            raise ConfigError(f"{where}: [{table}] must be a table")
        for k in keys:
            if not isinstance(cfg[table].get(k, ""), str):
                raise ConfigError(f"{where}: [{table}] {k} must be text")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,60}", cfg["atlas"]["short_name"]):
        raise ConfigError(f"{where}: [atlas] short_name must be letters, digits, '_', '-', '.' (it names the zip)")
    if not isinstance(cfg["topics"], dict) or not all(isinstance(v, dict) for v in cfg["topics"].values()):
        raise ConfigError(f"{where}: [topics.<key>] tables hold label = \"...\"")
    groups = cfg["groups"]
    if not isinstance(groups, list) or not all(isinstance(g, dict) and isinstance(g.get("name"), str)
                                               and isinstance(g.get("topics", []), list) for g in groups):
        raise ConfigError(f"{where}: each [[groups]] needs name = \"...\" and topics = [\"...\"]")
    if len(groups) > MAX_GROUPS:
        raise ConfigError(f"{where}: at most {MAX_GROUPS} [[groups]] (the citation map draws one panel each)")
    tasks = cfg["tasks"]
    if not isinstance(tasks, list) or not all(isinstance(t, dict) and all(isinstance(t.get(k), str) and t.get(k)
                                                                          for k in ("id", "title", "query"))
                                              for t in tasks):
        raise ConfigError(f"{where}: each [[tasks]] needs id, title and query (text)")
    ids = [t["id"] for t in tasks]
    if len(set(ids)) != len(ids):
        raise ConfigError(f"{where}: [[tasks]] ids must be unique")
    if not isinstance(cfg["pipeline"], dict):
        raise ConfigError(f"{where}: [pipeline] must be a table")
    unknown = sorted(set(cfg["pipeline"]) - set(GENERIC["pipeline"]))
    if unknown:
        raise ConfigError(f"{where}: unknown [pipeline] keys {unknown} (known: {sorted(GENERIC['pipeline'])})")
    return cfg


@lru_cache(maxsize=16)
def _config(path: str, stamp: float) -> dict:
    p = Path(path)
    raw = {}
    if p.is_file():
        try:
            raw = tomllib.loads(p.read_text(encoding="utf-8"))
        except tomllib.TOMLDecodeError as e:
            raise ConfigError(f"{p}: {e}") from None
    return _validate(_merge(GENERIC, raw), str(p))


def config(project: Optional[Path] = None) -> dict:
    """The project's atlas.toml over the generic defaults (a copy: callers may not change the cache)."""
    p = Path(project or project_dir()) / CONFIG
    try:
        stamp = p.stat().st_mtime
    except OSError:
        stamp = 0.0
    return copy.deepcopy(_config(str(p), stamp))


def papers_dir(project: Optional[Path] = None, legacy: Optional[Callable[[], Path]] = None) -> Path:
    """The project's PDF folder: $ATLAS_PAPERS, else atlas.toml [paths] papers (relative to the project), else
    `legacy()` (the BlueBoat atlas: $SVFR_BWM_PAPERS / the copy data_roots finds), else <project>/pdfs."""
    v = os.environ.get(ENV_PAPERS, "").strip()
    if v:
        return Path(v).expanduser()
    proj = Path(project or project_dir())
    p = config(proj)["paths"]["papers"].strip()
    if p:
        q = Path(os.path.expandvars(p)).expanduser()
        return q if q.is_absolute() else (proj / q).resolve()
    if legacy is not None and is_blueboat(proj):
        return Path(legacy())
    return proj / "pdfs"


def beside(papers: Path, suffix: str) -> Path:
    """A cache beside the PDF folder: beside(<x>/pdfs, 'text') -> <x>/pdfs_text."""
    papers = Path(papers)
    return papers.parent / f"{papers.name}_{suffix}"


def topic_keys(project: Optional[Path] = None) -> List[str]:
    """Every topic of the project: the papers/<topic>.json file names (not the _underscore ones), sorted."""
    d = Path(project or project_dir()) / "papers"
    return sorted(f.stem for f in d.glob("*.json") if not f.name.startswith("_")) if d.is_dir() else []


def topic_label(key: str, project: Optional[Path] = None, cfg: Optional[dict] = None) -> str:
    cfg = cfg or config(project)
    lab = (cfg["topics"].get(key) or {}).get("label")
    return str(lab) if lab else str(key).replace("_", " ").strip().capitalize()


def topic_labels(project: Optional[Path] = None) -> Dict[str, str]:
    cfg = config(project)
    keys = set(topic_keys(project)) | set(cfg["topics"])
    return {k: topic_label(k, cfg=cfg) for k in sorted(keys)}


def _row_counts(project: Path) -> Dict[str, int]:
    import json
    out = {}
    for k in topic_keys(project):
        try:
            data = json.loads((project / "papers" / f"{k}.json").read_text(encoding="utf-8"))
            out[k] = len(data) if isinstance(data, list) else 0
        except (OSError, ValueError):
            out[k] = 0
    return out


def topic_groups(project: Optional[Path] = None) -> Tuple[Tuple[str, Tuple[str, ...]], ...]:
    """The citation map's topic groups: atlas.toml [[groups]] when given; else one group per topic, the biggest
    first, with every topic past the sixth in a last 'Other topics' group (a paper no group names is drawn in the
    LAST group either way). Never empty: a project with no topics yet has one group, 'All papers'."""
    proj = Path(project or project_dir())
    cfg = config(proj)
    if cfg["groups"]:
        return tuple((str(g["name"]), tuple(str(t) for t in g.get("topics") or ())) for g in cfg["groups"])
    counts = _row_counts(proj)
    keys = sorted(counts, key=lambda k: (-counts[k], k))
    if not keys:
        return (("All papers", ()),)
    if len(keys) <= MAX_GROUPS:
        return tuple((topic_label(k, cfg=cfg), (k,)) for k in keys)
    head = keys[:MAX_GROUPS - 1]
    return tuple((topic_label(k, cfg=cfg), (k,)) for k in head) + (("Other topics", tuple(keys[MAX_GROUPS - 1:])),)


def tasks(project: Optional[Path] = None) -> List[Tuple[str, str, str]]:
    """The program tasks the atlas's Find tab offers as one click: [(id, title, query)]."""
    return [(t["id"], t["title"], t["query"]) for t in config(project)["tasks"]]


def pipeline(project: Optional[Path] = None) -> dict:
    return config(project)["pipeline"]


def contact_email() -> str:
    """The address the registries' 'polite pool' asks for in a request's User-Agent (Crossref, OpenAlex):
    $ATLAS_CONTACT_EMAIL; in this repository (the BlueBoat atlas beside the code) the owner's, as before -- read from
    report/boat_world_model/atlas.toml `[atlas] contact_email`, never written in code: this file ships in the kit and
    the public repository (owner 2026-10-15: no address in them); in an exported kit NOTHING unless the lab mate sets
    it."""
    v = os.environ.get("ATLAS_CONTACT_EMAIL", "").strip()
    if v:
        return v
    return config(BLUEBOAT)["atlas"].get("contact_email", "").strip() if BLUEBOAT.is_dir() else ""


def user_agent(tool: str) -> str:
    """'sonar-video-fusion-review/<tool> (mailto:...)' in this repository (unchanged); 'paper-atlas/<tool>' in a kit."""
    c = contact_email()
    return f"{'sonar-video-fusion-review' if BLUEBOAT.is_dir() else 'paper-atlas'}/{tool}" + (f" (mailto:{c})" if c else "")


def names(project: Optional[Path] = None) -> dict:
    """The page title / subtitle, the zip's base name and top folder, and its README's first line."""
    a = config(project)["atlas"]
    return {"title": a["title"], "subtitle": a["subtitle"], "short_name": a["short_name"],
            "bundle_title": a["bundle_title"]}
